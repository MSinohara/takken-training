import { initializeApp } from "firebase/app";
import { getDataConnect } from "firebase/data-connect";
import {
  adminSaveMemberSetting,
  adminSavePerson,
  adminSearchMemberCompanies,
  adminSearchPeople,
  adminListOrganizations,
  adminSaveOrganization,
  adminOrganizationMembers,
  adminAddMemberOrganization,
  adminAddPersonOrganization,
  adminMemberDetail,
  adminRemoveMemberOrganization,
  adminPersonOrganizations,
  adminRemovePersonOrganization,
  adminPeopleForMember,
  adminCreatePerson,
  adminImportMemberCompanies,
  adminDeactivateMissingMembers,
  adminImportPeople,
  adminValidateOrganizationImportMembers,
  adminReplaceOrganizationMembers,
  connectorConfig,
} from "./generated.js?v=33";
import { firebaseConfig } from "./config.js?v=17";
import { requireSqlAdmin } from "./admin-auth.js?v=16";

const app = initializeApp(firebaseConfig);
const dc = getDataConnect(app, connectorConfig);

function optional(value) {
  const text = String(value == null ? "" : value).trim();
  return text || null;
}

async function authorize() {
  const status = document.getElementById("status") || document.body;
  await requireSqlAdmin(app, status);
}

async function searchMembers(filters) {
  await authorize();
  const keyword = String(filters.keyword || "").trim();
  const variables = {
    keyword,
    active: true,
    limit: Number(filters.limit || 10),
    offset: Number(filters.offset || 0),
  };
  if (optional(filters.branch)) variables.branch = optional(filters.branch);
  if (filters.target !== "") variables.sendTarget = filters.target === "TRUE";
  if (filters.mailStatus === "NO_MAIL") variables.emailMissing = true;
  if (filters.mailStatus === "HAS_MAIL") variables.emailMissing = false;
  const result = await adminSearchMemberCompanies(dc, variables, { fetchPolicy: "SERVER_ONLY" });
  const data = result.data || {};
  return {
    ok: true,
    members: (data.rows || []).map((row) => ({
      memberNo: row.memberNo || "",
      companyName: row.companyName || "",
      representativeName: row.representativeName || "",
      mail: row.email || "",
      branch: row.branch || "",
      district: row.district || "",
      block: row.block || "",
      target: row.sendTarget ? "TRUE" : "FALSE",
      note: row.note || "",
      active: row.active,
    })),
    totalCount: Number((data.total && data.total[0] && data.total[0]._count) || 0),
  };
}

async function searchPeople(filters) {
  await authorize();
  const keyword = String(filters.keyword || "").trim();
  const variables = {
    keyword,
    active: true,
    limit: Number(filters.limit || 50),
    offset: Number(filters.offset || 0),
  };
  if (optional(filters.branch)) variables.branch = optional(filters.branch);
  if (filters.mailStatus === "NO_MAIL") variables.emailMissing = true;
  if (filters.mailStatus === "HAS_MAIL") variables.emailMissing = false;
  const result = await adminSearchPeople(dc, variables, { fetchPolicy: "SERVER_ONLY" });
  const data = result.data || {};
  return {
    ok: true,
    members: (data.rows || []).map((row) => ({
      personalId: row.personalId || "",
      memberNo: row.memberNo || "",
      companyName: (row.company && row.company.companyName) || "",
      personName: row.name || "",
      personType: row.personType || "",
      mail: row.email || "",
      active: row.active,
      source: row.source || "",
      note: row.note || "",
      autoGenerated: Boolean(row.autoGenerated),
      branch: (row.company && row.company.branch) || "",
      district: (row.company && row.company.district) || "",
      block: (row.company && row.company.block) || "",
    })),
    totalCount: Number((data.total && data.total[0] && data.total[0]._count) || 0),
  };
}

window.sqlAdminMaster = {
  importMembers: async (rows, onProgress) => {
    await authorize();
    const data = rows.map((row) => ({
      memberNo: String(row[0] || "").trim(), companyName: String(row[1] || "").trim(),
      representativeName: optional(row[2]), block: String(row[3] || "").trim(),
      branch: String(row[4] || "").trim(), district: optional(row[5]),
      email: optional(row[6]), active: true,
    }));
    const chunkSize = 100;
    for (let start = 0; start < data.length; start += chunkSize) {
      await adminImportMemberCompanies(dc, { data: data.slice(start, start + chunkSize) });
      if (onProgress) onProgress(Math.min(start + chunkSize, data.length), data.length);
    }
    const representatives = data.filter((row) => row.representativeName).map((row) => ({
      personalId: `${row.memberNo}-001`, memberNo: row.memberNo, name: row.representativeName,
      email: row.email, personType: "代表者", approvalStatus: "承認済み", active: true,
      source: "会員マスタCSV", note: null, autoGenerated: true,
    }));
    for (let start = 0; start < representatives.length; start += chunkSize) {
      await adminImportPeople(dc, { data: representatives.slice(start, start + chunkSize) });
    }
    await adminDeactivateMissingMembers(dc, { memberNos: data.map((row) => row.memberNo) });
    return { ok: true, imported: data.length, message: "会員マスタをSQLへ取り込みました。" };
  },
  importPeople: async (rows) => {
    await authorize();
    const chunkSize = 100;
    for (let start = 0; start < rows.length; start += chunkSize) {
      await adminImportPeople(dc, { data: rows.slice(start, start + chunkSize) });
    }
    return { ok: true, saved: rows.length, message: `重複候補を個人会員マスタへ反映しました。登録 ${rows.length}件。` };
  },
  createPerson: async (data) => {
    await authorize();
    const memberNo = String(data.memberNo || "").trim();
    if (!memberNo) throw new Error("会社を選択してください。");
    if (!String(data.name || "").trim()) throw new Error("氏名を入力してください。");
    for (let attempt = 0; attempt < 3; attempt += 1) {
      const result = await adminPeopleForMember(dc, { memberNo }, { fetchPolicy: "SERVER_ONLY" });
      const found = result.data || {};
      if (!found.memberCompany) throw new Error("選択した会社が見つかりません。");
      const used = new Set((found.people || []).map((row) => row.personalId));
      let number = 2;
      while (used.has(`${memberNo}-${String(number).padStart(3, "0")}`)) number += 1;
      const personalId = `${memberNo}-${String(number).padStart(3, "0")}`;
      try {
        await adminCreatePerson(dc, {
          personalId, memberNo, name: String(data.name).trim(), email: optional(data.email),
          personType: optional(data.personType) || "社員", approvalStatus: "承認済み",
          active: data.active !== false, source: optional(data.source) || "手入力",
          note: optional(data.note), autoGenerated: false,
        });
        return { ok: true, personalId, message: `${personalId} として登録しました。` };
      } catch (error) {
        if (attempt === 2) throw error;
      }
    }
    throw new Error("個人IDを採番できませんでした。もう一度お試しください。");
  },
  personOrganizations: async (personalId) => {
    await authorize();
    const memberNo = String(personalId).replace(/-\d+$/, "");
    const isRepresentative = /-001$/.test(personalId);
    const result = await adminPersonOrganizations(dc, { personalId, memberNo }, { fetchPolicy: "SERVER_ONLY" });
    const data = result.data || {};
    if (!data.person) return { ok: false, message: "個人会員が見つかりません。" };
    const rows = isRepresentative ? data.memberSelected : data.personSelected;
    const selected = new Set((rows || []).map((row) => row.orgId));
    return {
      ok: true,
      personalId: data.person.personalId,
      companyName: (data.person.company && data.person.company.companyName) || "",
      personName: data.person.name || "",
      isRepresentative,
      organizations: (data.organizations || []).filter((org) => org.active).map((org) => ({
        orgId: org.orgId, orgName: org.orgName, selected: selected.has(org.orgId),
      })),
    };
  },
  savePersonalOrganizations: async (personalId, orgIds) => {
    await authorize();
    const detail = await window.sqlAdminMaster.personOrganizations(personalId);
    if (!detail.ok) return detail;
    const before = new Set(detail.organizations.filter((org) => org.selected).map((org) => org.orgId));
    const after = new Set(orgIds);
    const isRepresentative = /-001$/.test(personalId);
    const memberNo = String(personalId).replace(/-\d+$/, "");
    for (const orgId of after) {
      if (before.has(orgId)) continue;
      if (isRepresentative) await adminAddMemberOrganization(dc, { memberNo, orgId });
      else await adminAddPersonOrganization(dc, { personalId, orgId, source: "個人会員マスタ" });
    }
    for (const orgId of before) {
      if (after.has(orgId)) continue;
      if (isRepresentative) await adminRemoveMemberOrganization(dc, { memberNo, orgId });
      else await adminRemovePersonOrganization(dc, { personalId, orgId });
    }
    return { ok: true, message: "個人所属を保存しました。" };
  },
  memberDetail: async (memberNo) => {
    await authorize();
    const result = await adminMemberDetail(dc, { memberNo }, { fetchPolicy: "SERVER_ONLY" });
    const data = result.data || {};
    if (!data.memberCompany) return { ok: false, message: "会員情報が見つかりません。" };
    const selected = new Set((data.selected || []).map((row) => row.orgId));
    const member = data.memberCompany;
    return {
      ok: true,
      member: {
        memberNo: member.memberNo, companyName: member.companyName,
        representativeName: member.representativeName || "", mail: member.email || "",
        branch: member.branch || "", district: member.district || "", block: member.block || "",
        target: member.sendTarget ? "TRUE" : "FALSE", note: member.note || "", active: member.active,
      },
      organizations: (data.organizations || []).filter((org) => org.active).map((org) => ({
        orgId: org.orgId, orgName: org.orgName, selected: selected.has(org.orgId),
      })),
    };
  },
  saveMemberOrganizations: async (memberNo, orgIds) => {
    await authorize();
    const detail = await window.sqlAdminMaster.memberDetail(memberNo);
    if (!detail.ok) return detail;
    const before = new Set(detail.organizations.filter((org) => org.selected).map((org) => org.orgId));
    const after = new Set(orgIds);
    for (const orgId of after) {
      if (!before.has(orgId)) await adminAddMemberOrganization(dc, { memberNo, orgId });
    }
    for (const orgId of before) {
      if (!after.has(orgId)) await adminRemoveMemberOrganization(dc, { memberNo, orgId });
    }
    return { ok: true, message: "会員設定と所属組織を保存しました。" };
  },
  listOrganizations: async () => {
    await authorize();
    const result = await adminListOrganizations(dc, {}, { fetchPolicy: "SERVER_ONLY" });
    return { ok: true, organizations: (result.data.organizations || []).map((o) => ({
      orgId: o.orgId, orgName: o.orgName, senderName: o.senderName,
      active: o.active ? "TRUE" : "FALSE", hostAvailable: o.hostAvailable ? "TRUE" : "FALSE",
      csvImportName: o.csvImportName || "", csvImportMode: o.csvImportMode || "所属入替",
      createdAt: o.createdAt || "", updatedAt: o.updatedAt || "",
    })) };
  },
  saveOrganization: async (data) => {
    await authorize();
    const orgId = data.orgId || `ORG-${Date.now()}`;
    await adminSaveOrganization(dc, {
      orgId, orgName: data.orgName, senderName: data.senderName,
      active: data.active !== "FALSE", hostAvailable: data.hostAvailable === "TRUE",
      csvImportName: optional(data.csvImportName), csvImportMode: optional(data.csvImportMode),
      updatedAt: new Date().toISOString(),
    });
    return { ok: true, orgId, message: data.orgId ? "組織を更新しました。" : "組織を登録しました。" };
  },
  organizationMembers: async (orgId) => {
    await authorize();
    const result = await adminOrganizationMembers(dc, { orgId }, { fetchPolicy: "SERVER_ONLY" });
    const data = result.data || {};
    const byId = new Map();
    (data.companyRows || []).forEach(({ member }) => {
      const personalId = `${member.memberNo}-001`;
      byId.set(personalId, { memberNo: member.memberNo, companyName: member.companyName,
        personalId, personName: member.representativeName || "", personType: "代表者",
        branch: member.branch, district: member.district || "", mail: member.email || "" });
    });
    (data.personRows || []).forEach(({ person }) => byId.set(person.personalId, {
      memberNo: person.memberNo, companyName: person.company.companyName, personalId: person.personalId,
      personName: person.name, personType: person.personType || "", branch: person.company.branch,
      district: person.company.district || "", mail: person.email || "",
    }));
    return { ok: true, members: [...byId.values()] };
  },
  addPeopleToOrganization: async (orgId, personalIds) => {
    await authorize();
    for (const personalId of personalIds) {
      if (/-001$/.test(personalId)) {
        await adminAddMemberOrganization(dc, { memberNo: personalId.replace(/-001$/, ""), orgId });
      } else {
        await adminAddPersonOrganization(dc, { personalId, orgId, source: "組織設定画面" });
      }
    }
    return { ok: true, message: `所属個人を追加しました。追加 ${personalIds.length}件。` };
  },
  replaceOrganizationMembers: async (orgId, memberNos) => {
    await authorize();
    const uniqueMemberNos = [...new Set(memberNos.map((value) => String(value || "").trim()).filter(Boolean))];
    const valid = new Set();
    const chunkSize = 500;
    for (let start = 0; start < uniqueMemberNos.length; start += chunkSize) {
      const chunk = uniqueMemberNos.slice(start, start + chunkSize);
      const result = await adminValidateOrganizationImportMembers(dc, { memberNos: chunk }, { fetchPolicy: "SERVER_ONLY" });
      (result.data.rows || []).forEach((row) => valid.add(row.memberNo));
    }
    const unknownList = uniqueMemberNos.filter((memberNo) => !valid.has(memberNo));
    const data = [...valid].map((memberNo) => ({ memberNo, orgId }));
    const result = await adminReplaceOrganizationMembers(dc, { orgId, data });
    const response = result.data || {};
    return {
      ok: true,
      message: "所属組織をSQLで更新しました。",
      deleted: Number((response.deleted && response.deleted._count) || 0),
      imported: data.length,
      unknown: unknownList.length,
      unknownList: unknownList.slice(0, 20),
    };
  },
  saveMemberSetting: async (data) => {
    await authorize();
    await adminSaveMemberSetting(dc, {
      memberNo: data.memberNo,
      email: optional(data.email),
      sendTarget: Boolean(data.sendTarget),
      note: optional(data.note),
    });
    return { ok: true };
  },
  savePerson: async (data) => {
    await authorize();
    await adminSavePerson(dc, data);
    return { ok: true };
  },
  searchMembers,
  searchPeople,
};
